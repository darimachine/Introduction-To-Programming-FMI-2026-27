// Task4HW1.cpp : Simple arithmetic operations with 2 numbers
// Group 5

#include <iostream>
using namespace std;

int main()
{
    int num1, num2;
    cin >> num1 >> num2;

    cout << "Addition: " << (num1 + num2) << endl;
    cout << "Substraction: " << (num1 - num2) << endl;
    cout << "Multiplication: " << (num1 * num2) << endl;
    cout << "Division: " << (num1 / num2) << endl;

    return 0;
}
